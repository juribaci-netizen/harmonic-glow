import assert from 'node:assert/strict'
import { assignedSlots,dayValues,parseRange,visible,bratislavaNow,slotNote,fieldRect,geometry,type Entry } from '../lib/epc/model'
const e=(patch:Partial<Entry>):Entry=>({id:1,date:'2026-06-01',type:'rehearsal',title:'Skúška',hours:'3',status:'auto',notes:null,startTime:'09:00',endTime:'12:00',...patch})
const now={date:'2026-06-01',minutes:11*60}
assert.equal(visible(e({}),now),false)
assert.equal(visible(e({}),{...now,minutes:720}),true)
assert.equal(visible(e({date:'2026-06-02'}),now),false)
assert.equal(visible(e({date:'2026-06-02',status:'manual'}),now),true)
assert.equal(visible(e({status:'removed'}),now),false)
assert.equal(visible(e({status:'suggested'}),now),false)
const second=e({id:2,type:'manual-service',title:'Manuálne pridaná 2. služba',status:'manual',startTime:null,endTime:null})
assert.equal(assignedSlots([second],'service')[0],undefined)
assert.equal(assignedSlots([second],'service')[1]?.id,2)
const ip2=e({id:2,type:'individual',status:'manual',startTime:'08:00',endTime:'10:00',notes:slotNote(null,'ip',2)})
assert.equal(assignedSlots([ip2],'ip')[1]?.id,2)
const removed=e({type:'individual',status:'removed',startTime:null,endTime:null,notes:slotNote(null,'ip',1)})
assert.deepEqual(dayValues([removed,ip2],'2026-06-01',now).ranges,['','08:00-10:00'])
assert.deepEqual(dayValues([e({type:'individual',status:'manual',startTime:'15:15',endTime:'17:45'})],'2026-06-01',now).ranges,['','15:15-17:45'])
const auto=e({id:3,type:'individual',startTime:null,endTime:null})
assert.deepEqual(dayValues([auto],'2026-06-01',now).ranges,['',''])
assert.deepEqual(dayValues([e({}),auto],'2026-06-01',{date:'2026-06-02',minutes:0}).ranges,['','14:00-17:00'])
assert.deepEqual(parseRange('20:00-24:00'),['20:00','24:00'])
for(const bad of ['12:00-08:00','12:99-14:00','24:01-25:00','12:00','wrong'])assert.equal(parseRange(bad),null)
assert.deepEqual(parseRange(''),[null,null])
assert.equal(bratislavaNow(new Date('2026-09-10T23:00:00Z')).date,'2026-09-11')
assert.equal(Object.keys(geometry.fields).length,132)
assert.deepEqual(fieldRect('Check Box 1.1'),{x:110.5451,y:666.3561,width:156.0731-110.5451,height:683.0841-666.3561,top:841.9201-683.0841})
console.log('EPC model: progressive filling, manual overrides, column identity, time validation and 132 field coordinates passed.')
